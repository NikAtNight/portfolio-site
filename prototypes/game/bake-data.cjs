// PROTOTYPE tool. Writes world3d-data.js: boss stats and battle scripts for the 3D world,
// read from the 2D prototype so the two never disagree. Run after changing a boss's moves
// in raid-sprites.js or a Raid Log entry in index.html:  node bake-data.cjs
// Needs a playwright install and a Chromium binary; both paths are read from the env or guessed.
const path = require('path'), fs = require('fs'), os = require('os');
const npx = path.join(os.homedir(), '.npm/_npx');
const pwDir = process.env.PLAYWRIGHT_DIR || fs.readdirSync(npx).map(d => path.join(npx, d, 'node_modules/playwright')).find(p => fs.existsSync(p));
const exe = process.env.CHROMIUM || path.join(os.homedir(), 'Library/Caches/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-mac-arm64/chrome-headless-shell');
const { chromium } = require(pwDir);

(async () => {
  const browser = await chromium.launch({ executablePath: exe });
  const page = await browser.newPage();
  await page.goto('file://' + path.join(__dirname, 'index.html'));
  await page.waitForFunction(() => window.gpGame && gpGame.BOSSES.length === 9);
  const bosses = await page.evaluate(() => gpGame.BOSSES.map((b, i) => ({
    id: b.id, unit: b.unit, hp: b.hp, aura: b.aura,
    title: gpGame.entries[i].querySelector('h3').textContent,
    tag: gpGame.entries[i].querySelector('.tag').textContent,
    moves: b.moves.map(m => ({ w: m.w, text: m.text, dmg: m.dmg || 0, crit: !!m.crit, miss: m.miss || '' })),
  })));
  await browser.close();
  const file = path.join(__dirname, 'world3d-data.js');
  fs.writeFileSync(file, '// GENERATED by bake-data.cjs. Do not edit by hand.\nwindow.W3D_DATA = ' + JSON.stringify({ bosses }, null, 1) + ';\n');
  console.log(`wrote ${file}: ${bosses.length} bosses`);
})().catch(e => { console.error(e); process.exit(1); });
